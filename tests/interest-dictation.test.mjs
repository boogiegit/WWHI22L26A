import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const stored=new Map(), elements={};
for(const id of ['ann-body','ann-writing-status','ann-dictate','ann-publish','ann-polish'])elements[id]={value:'Existing note.',textContent:'',setAttribute(){},focus(){},isConnected:true};
let speech;
class Speech {constructor(){speech=this;}start(){this.onstart();}stop(){this.onend();}}
const ctx=vm.createContext({window:{SpeechRecognition:Speech},document:{getElementById:id=>elements[id]},localStorage:{getItem:k=>stored.get(k),setItem:(k,v)=>stored.set(k,v)},trackAnalytics(){},escapeHtml:s=>s,renderApp(){},USE_REMOTE_STORAGE:true,ADMIN_MODE:false,activeTab:'experiences',traditionalEuropeExperiences:()=>[{experienceId:'a',displayTitle:'First'},{experienceId:'b',displayTitle:'Second'}],authRequest:async(action,data)=>action==='interestMine'?{items:[]}:{},announcementRandom:()=> 'a'.repeat(64)});
vm.runInContext(fs.readFileSync('js/services/announcements.js','utf8'),ctx);
vm.runInContext("updateAnnouncementPreview=()=>{};announcementRandom=()=> 'a'.repeat(64);",ctx);
vm.runInContext(fs.readFileSync('js/services/experience-interest.js','utf8'),ctx);
await vm.runInContext("openInterest('a')",ctx);
assert.match(vm.runInContext('interestForm()',ctx),/id="interest-name"/);
vm.runInContext("interestState.name='Sam and Alex';interestState.people=2;",ctx);
await vm.runInContext('saveInterest(false)',ctx);
vm.runInContext("interestState.name='';interestState.profileReady=false;interestState.people=1;",ctx);
await vm.runInContext("openInterest('b')",ctx);
assert.equal(vm.runInContext('interestState.name',ctx),'Sam and Alex');
assert.equal(vm.runInContext('interestState.people',ctx),2);
assert.doesNotMatch(vm.runInContext('interestForm()',ctx),/id="interest-name"/);
vm.runInContext('editInterestProfile()',ctx);
assert.match(vm.runInContext('interestForm()',ctx),/id="interest-name"/);
vm.runInContext('dictateAnnouncement()',ctx);
assert.equal(speech.continuous,true);assert.equal(speech.interimResults,true);
assert.match(elements['ann-writing-status'].textContent,/Listening/);
const result=(text,final)=>Object.assign([{transcript:text}],{isFinal:final});
speech.onresult({results:[result('Meet in',false)]});
assert.equal(elements['ann-body'].value,'Existing note. Meet in');
speech.onresult({results:[result('Meet in the lobby.',true),result('Bring coats',false)]});
assert.equal(elements['ann-body'].value,'Existing note. Meet in the lobby. Bring coats');
vm.runInContext('dictateAnnouncement()',ctx);
assert.equal(elements['ann-body'].readOnly,false);
assert.match(elements['ann-writing-status'].textContent,/stopped/);
assert.equal(vm.runInContext('announcementState.draft.body',ctx),elements['ann-body'].value);
vm.runInContext('dictateAnnouncement()',ctx);
speech.onerror({error:'not-allowed'});speech.onend();
assert.match(elements['ann-writing-status'].textContent,/not allowed/);
assert.equal(elements['ann-publish'].disabled,false);
console.log('PASS: remembered party across reload/experiences, editable identity, live interim dictation without duplicate words, stop and denied microphone recovery.');
